/**
 * extract_content.js
 * Reads the single source of truth (content.js) and mirrors every top-level
 * section into clean, pretty-printed JSON files under data/.
 *
 * This script is READ-ONLY toward content.js. It never writes or modifies it.
 * Re-run after editing content.js:   node extract_content.js
 */

const fs = require("fs");
const path = require("path");
const { CONTENT } = require("./content.js");

const ROOT = __dirname;
const OUT_DIR = path.join(ROOT, "data");

function typeOf(value) {
  if (Array.isArray(value)) return "array";
  if (value === null) return "null";
  return typeof value;
}

function countOf(value) {
  if (Array.isArray(value)) return value.length;
  if (value && typeof value === "object") return Object.keys(value).length;
  return 1;
}

function safeName(key) {
  return String(key).replace(/[^A-Za-z0-9_-]/g, "_");
}

function main() {
  if (!CONTENT || typeof CONTENT !== "object") {
    throw new Error("content.js did not export a CONTENT object");
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const keys = Object.keys(CONTENT).sort();
  const index = {};

  for (const key of keys) {
    const value = CONTENT[key];
    const file = `${safeName(key)}.json`;
    const target = path.join(OUT_DIR, file);
    fs.writeFileSync(target, JSON.stringify(value, null, 2) + "\n", "utf8");
    index[key] = {
      file: `data/${file}`,
      type: typeOf(value),
      count: countOf(value),
    };
  }

  const indexDoc = {
    source: "content.js",
    note: "Generated by extract_content.js. Do not edit by hand; edit content.js and re-run.",
    generatedAt: new Date().toISOString(),
    sectionCount: keys.length,
    sections: index,
  };
  fs.writeFileSync(
    path.join(OUT_DIR, "index.json"),
    JSON.stringify(indexDoc, null, 2) + "\n",
    "utf8"
  );

  console.log(`[extract] ${keys.length} sections -> ${OUT_DIR}`);
}

main();